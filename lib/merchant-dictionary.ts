const NORMALIZED_DICT: [string, string][] = RAW_DICTIONARY.map(([k, v]) => [normalize(k), v])

export function classifyByDictionary(merchant: string): string | null {
  const norm = normalize(merchant)
  // 完全一致
  for (const [key, cat] of NORMALIZED_DICT) {
    if (norm === key) return cat
  }
  // 部分一致
  for (const [key, cat] of NORMALIZED_DICT) {
    if (norm.includes(key) || key.includes(norm)) return cat
  }
  return null
}
